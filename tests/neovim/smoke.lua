local repo = vim.fn.fnamemodify(vim.fn.stdpath('config'), ':p'):gsub('/nvim/?$', '')
repo = vim.uv.fs_realpath(repo) or repo
-- The config directory may be a symlink; resolve it before finding fixtures.
repo = vim.fs.dirname(vim.uv.fs_realpath(vim.fn.stdpath('config')))
local passed = 0
local function check(value, message)
  assert(value, message)
  passed = passed + 1
end
local function edit(path)
  vim.cmd.edit(vim.fn.fnameescape(repo .. '/tests/neovim/' .. path))
end
local function normal(keys) vim.cmd.normal({ args = { keys } }) end
local function escape() vim.cmd.normal({ args = { '\27' }, bang = true }) end
local function run()
  check(vim.g.colors_name == require('config.theme').selected(), 'Selected theme is active')
  for _, file in ipairs(vim.fn.glob(repo .. '/nvim/lua/**/*.lua', false, true)) do
    check(loadfile(file) ~= nil, 'Lua syntax: ' .. file)
  end
  require('lazy').load({ plugins = { 'blink.cmp', 'nvim-lspconfig', 'gitsigns.nvim', 'diffview.nvim', 'gitgraph.nvim', 'agentic.nvim', 'which-key.nvim' } })
  vim.wait(100, function() return false end)
  check(require('blink.cmp.config').fuzzy.implementation == 'lua', 'Completion has no binary download')
  check(type(require('agentic').add_selection) == 'function', 'Agent selection API exists')
  check(type(require('agentic').new_session_with_provider) == 'function', 'Agent provider API exists')
  vim.api.nvim_buf_set_lines(0, 0, -1, false, { '    value' })
  vim.api.nvim_win_set_cursor(0, { 1, 4 })
  vim.api.nvim_feedkeys(vim.keycode('i<S-Tab><Esc>'), 'xt', false)
  check(vim.api.nvim_get_current_line() == '  value', 'Shift-Tab dedents instead of deleting or inserting text')
  vim.bo.modified = false
  edit('structure.c')
  local s = require('config.structure')
  local functions = s.ranges('function', false)
  local classes = s.ranges('class', false)
  check(#functions == 2, 'C function count')
  check(#classes == 3, 'C nested struct and union count')
  vim.api.nvim_win_set_cursor(0, { 10, 2 })
  normal('"zyaf')
  check(vim.fn.getreg('z'):match('int first%(int value%)') ~= nil, 'Operator-pending yaf includes signature')
  check(not vim.fn.getreg('z'):match('int second'), 'yaf excludes next function')
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
  normal(']m')
  check(vim.fn.line('.') == 9, ']m function jump')
  normal(']m')
  check(vim.fn.line('.') == 13, ']m next function')
  normal('[m')
  check(vim.fn.line('.') == 9, '[m previous function')
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
  normal('2]m')
  check(vim.fn.line('.') == 13, 'Counted jump')
  normal(']m')
  check(vim.fn.line('.') == 13, 'No boundary wrapping')
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
  normal(']]')
  check(vim.fn.line('.') == 2, 'Nested structure jump')
  vim.api.nvim_win_set_cursor(0, { 4, 4 })
  normal('"zyac')
  check(vim.fn.getreg('z'):match('struct Inner') and vim.fn.getreg('z'):match('}'), 'Nested type object')

  edit('structure.cpp')
  functions = s.ranges('function', false)
  classes = s.ranges('class', false)
  check(#functions == 3, 'C++ named functions exclude lambda')
  check(#s.ranges('function', true) == 4, 'C++ lambda available for selection')
  check(#classes == 3, 'C++ template, nested struct and union')
  vim.api.nvim_win_set_cursor(0, { 4, 2 })
  normal('"zyaf')
  check(vim.fn.getreg('z'):match('^template') ~= nil, 'Function includes template header')
  check(not vim.fn.getreg('z'):match('A comment'), 'Function excludes preceding comment')
  vim.api.nvim_win_set_cursor(0, { 12, 2 })
  normal('"zyac')
  check(vim.fn.getreg('z'):match('^template') and vim.fn.getreg('z'):match('};$'), 'Template struct includes closing semicolon')
  vim.api.nvim_win_set_cursor(0, { 14, 36 })
  normal('"zyaf')
  check(vim.fn.getreg('z'):match('^%[%]') ~= nil, 'Selection inside lambda chooses lambda')
  vim.api.nvim_win_set_cursor(0, { 3, 0 })
  normal(']m')
  check(vim.fn.line('.') == 13, 'Navigation skips lambda and reaches member function')
  normal(']m')
  check(vim.fn.line('.') == 24, 'Next named function skips lambda')
  escape()
  check(vim.fn.maparg('<C-p>', 'i') ~= '', 'Insert-mode file search exists')
  check(vim.fn.maparg('<C-S-p>', 'i') == '', 'Extended keys disabled by default')
  check(vim.fn.isdirectory(vim.fn.stdpath('state') .. '/undo') == 1, 'Persistent undo directory exists')
  print(('PASS: %d assertions'):format(passed))
end
local ok, err = xpcall(run, debug.traceback)
if not ok then vim.api.nvim_err_writeln(err); vim.cmd.cquit(1) else vim.cmd.qa({ bang = true }) end
